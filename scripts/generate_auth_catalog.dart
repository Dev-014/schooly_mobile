import 'dart:convert';
import 'dart:io';

void main() {
  final inputPath = 'scripts/auth-catalog.json';
  final outputPath = 'lib/core/auth/permissions.dart';

  final jsonStr = File(inputPath).readAsStringSync();
  final catalog = jsonDecode(jsonStr);

  final permissions = catalog['permissions'] as List;

  final Map<String, Map<String, Map<String, String>>> grouped = {};

  for (final p in permissions) {
    final mod = toCamelCase(p['module']);
    final res = toCamelCase(p['resource']);
    final act = toCamelCase(p['action']);

    grouped.putIfAbsent(mod, () => {});
    grouped[mod]!.putIfAbsent(res, () => {});
    grouped[mod]![res]![act] = p['key'];
  }

  final sb = StringBuffer();
  sb.writeln('// AUTO-GENERATED PERMISSIONS CATALOG');
  sb.writeln(
    '// Do not edit this file directly. Update auth-catalog.json and regenerate.',
  );
  sb.writeln();

  sb.writeln('class Permissions {');
  for (final mod in grouped.keys) {
    final modClassName = '_\$${toPascalCase(mod)}Module';
    sb.writeln('  static const $mod = $modClassName();');
  }
  sb.writeln('}');
  sb.writeln();

  for (final mod in grouped.keys) {
    final modClassName = '_\$${toPascalCase(mod)}Module';
    sb.writeln('class $modClassName {');
    sb.writeln('  const $modClassName();');
    final resources = grouped[mod]!;
    for (final res in resources.keys) {
      final resClassName =
          '_\$${toPascalCase(mod)}${toPascalCase(res)}Resource';
      sb.writeln('  final $res = const $resClassName();');
    }
    sb.writeln('}');
    sb.writeln();

    for (final res in resources.keys) {
      final resClassName =
          '_\$${toPascalCase(mod)}${toPascalCase(res)}Resource';
      sb.writeln('class $resClassName {');
      sb.writeln('  const $resClassName();');
      final actions = resources[res]!;
      for (final act in actions.keys) {
        sb.writeln('  final String $act = \'${actions[act]}\';');
      }
      sb.writeln('}');
      sb.writeln();
    }
  }

  // Modules:
  sb.writeln('class AuthModules {');
  final modules = (catalog['modules'] as List)
      .map((e) => e['key'] as String)
      .toList();
  for (final m in modules) {
    sb.writeln('  static const String ${toCamelCase(m)} = \'$m\';');
  }
  sb.writeln(
    '  static const List<String> all = [${modules.map((e) => "'$e'").join(', ')}];',
  );
  sb.writeln('}');
  sb.writeln();

  // Scopes:
  sb.writeln('class AuthScopes {');
  final scopes = (catalog['scopes'] as List)
      .map((e) => e['key'] as String)
      .toList();
  for (final s in scopes) {
    String propName = toCamelCase(s);
    if (propName == 'class') propName = 'classScope';
    sb.writeln('  static const String ${propName} = \'$s\';');
  }
  sb.writeln(
    '  static const List<String> all = [${scopes.map((e) => "'$e'").join(', ')}];',
  );
  sb.writeln('}');
  sb.writeln();

  // Assignment Types:
  sb.writeln('class AuthAssignmentTypes {');
  final assignmentTypes = (catalog['assignment_types'] as List)
      .map((e) => e['key'] as String)
      .toList();
  for (final a in assignmentTypes) {
    sb.writeln('  static const String ${toCamelCase(a)} = \'$a\';');
  }
  sb.writeln(
    '  static const List<String> all = [${assignmentTypes.map((e) => "'$e'").join(', ')}];',
  );
  sb.writeln('}');
  sb.writeln();

  final file = File(outputPath);
  file.createSync(recursive: true);
  file.writeAsStringSync(sb.toString());
  print('Generated $outputPath successfully from canonical manifest.');
}

String toCamelCase(String str) {
  List<String> parts = str.split(RegExp(r'[_\s\-]+'));
  if (parts.isEmpty) return '';
  String result = parts[0].toLowerCase();
  for (int i = 1; i < parts.length; i++) {
    String p = parts[i];
    if (p.isNotEmpty) {
      result += p.substring(0, 1).toUpperCase() + p.substring(1).toLowerCase();
    }
  }
  return result;
}

String toPascalCase(String str) {
  List<String> parts = str.split(RegExp(r'[_\s\-]+'));
  String result = '';
  for (int i = 0; i < parts.length; i++) {
    String p = parts[i];
    if (p.isNotEmpty) {
      result += p.substring(0, 1).toUpperCase() + p.substring(1).toLowerCase();
    }
  }
  return result;
}
